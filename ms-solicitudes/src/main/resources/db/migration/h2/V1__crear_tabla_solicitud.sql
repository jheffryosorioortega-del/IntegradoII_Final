-- ms-solicitudes · esquema inicial · dialecto H2 (respaldo de desarrollo)
CREATE TABLE solicitud (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo             VARCHAR(20),
    cliente_id         BIGINT       NOT NULL,
    cliente_nombre     VARCHAR(60)  NOT NULL,
    cliente_telefono   VARCHAR(9)   NOT NULL,
    categoria          VARCHAR(20)  NOT NULL,
    descripcion        VARCHAR(600),
    direccion_servicio VARCHAR(120),
    urgencia           VARCHAR(10)  NOT NULL,
    estado             VARCHAR(25)  NOT NULL,
    fecha_creacion     TIMESTAMP(6) NOT NULL,
    CONSTRAINT uk_solicitud_codigo UNIQUE (codigo),
    CONSTRAINT ck_solicitud_categoria CHECK (categoria IN
        ('GASFITERIA', 'CISTERNAS', 'BOMBAS', 'AGUA_CALIENTE', 'ELECTRICIDAD', 'MANTENIMIENTO')),
    CONSTRAINT ck_solicitud_urgencia CHECK (urgencia IN ('BAJA', 'MEDIA', 'ALTA')),
    CONSTRAINT ck_solicitud_estado CHECK (estado IN
        ('REGISTRADA', 'PENDIENTE_EVALUACION', 'COTIZADA', 'APROBADA', 'PROGRAMADA', 'EN_EJECUCION', 'CERRADA'))
);
CREATE INDEX idx_solicitud_estado ON solicitud (estado);
CREATE INDEX idx_solicitud_fecha ON solicitud (fecha_creacion);
CREATE INDEX idx_solicitud_cliente ON solicitud (cliente_id);
