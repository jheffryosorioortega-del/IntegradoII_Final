-- Tecnico asignado e historial de cambios (version H2, solo para las pruebas automaticas).
ALTER TABLE solicitud ADD tecnico_correo VARCHAR(120) NULL;
ALTER TABLE solicitud ADD tecnico_nombre VARCHAR(60) NULL;

CREATE TABLE solicitud_historial (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    solicitud_id BIGINT       NOT NULL,
    fecha        TIMESTAMP(6) NOT NULL,
    usuario      VARCHAR(120) NOT NULL,
    accion       VARCHAR(10)  NOT NULL,
    anterior     VARCHAR(100),
    nuevo        VARCHAR(100),
    CONSTRAINT fk_historial_solicitud FOREIGN KEY (solicitud_id) REFERENCES solicitud (id) ON DELETE CASCADE,
    CONSTRAINT ck_historial_accion CHECK (accion IN ('CREACION', 'ESTADO', 'TECNICO'))
);
CREATE INDEX idx_historial_solicitud ON solicitud_historial (solicitud_id, fecha);

