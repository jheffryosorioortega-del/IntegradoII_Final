-- Fotos que el cliente adjunta como evidencia. Se guardan en la propia base de ms-solicitudes.
CREATE TABLE solicitud_foto (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    solicitud_id BIGINT NOT NULL REFERENCES solicitud (id) ON DELETE CASCADE,
    nombre VARCHAR(100) NOT NULL,
    tipo VARCHAR(20) NOT NULL,
    tamano INTEGER NOT NULL,
    contenido VARBINARY(7000000) NOT NULL,
    fecha_creacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_foto_tipo CHECK (tipo IN ('image/jpeg', 'image/png', 'image/webp'))
);
CREATE INDEX ix_foto_solicitud ON solicitud_foto (solicitud_id);
