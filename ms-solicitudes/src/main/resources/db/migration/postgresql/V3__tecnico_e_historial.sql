-- Tecnico asignado e historial de cambios. Extension aditiva: las solicitudes existentes quedan sin tecnico
-- y con una primera linea de historial "CREACION" tomada de su fecha de creacion.
--
-- tecnico_correo / tecnico_nombre son una COPIA del usuario de ms-usuarios (otra base de datos, sin clave foranea),
-- igual que cliente_nombre y cliente_telefono.
ALTER TABLE solicitud ADD COLUMN tecnico_correo VARCHAR(120);
ALTER TABLE solicitud ADD COLUMN tecnico_nombre VARCHAR(60);

CREATE TABLE solicitud_historial (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    solicitud_id BIGINT       NOT NULL,
    fecha        TIMESTAMP(6) NOT NULL,
    usuario      VARCHAR(120) NOT NULL,
    accion       VARCHAR(10)  NOT NULL,
    anterior     VARCHAR(100),
    nuevo        VARCHAR(100),
    -- Aqui SI hay clave foranea: solicitud e historial viven en la misma base.
    CONSTRAINT fk_historial_solicitud FOREIGN KEY (solicitud_id) REFERENCES solicitud (id) ON DELETE CASCADE,
    CONSTRAINT ck_historial_accion CHECK (accion IN ('CREACION', 'ESTADO', 'TECNICO'))
);
CREATE INDEX idx_historial_solicitud ON solicitud_historial (solicitud_id, fecha);

INSERT INTO solicitud_historial (solicitud_id, fecha, usuario, accion, anterior, nuevo)
SELECT id, fecha_creacion, 'sistema', 'CREACION', NULL, 'REGISTRADA' FROM solicitud;
