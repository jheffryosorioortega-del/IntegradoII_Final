-- ms-clientes - esquema inicial - PostgreSQL
-- telefono es UNIQUE: la base de datos impide dos clientes con el mismo telefono
-- aunque dos peticiones lleguen a la vez (la validacion de la aplicacion sola no lo garantiza).
CREATE TABLE cliente (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre         VARCHAR(60)  NOT NULL,
    telefono       VARCHAR(9)   NOT NULL,
    correo         VARCHAR(120),
    direccion      VARCHAR(120),
    distrito       VARCHAR(40),
    fecha_registro TIMESTAMP(6) NOT NULL,
    CONSTRAINT uk_cliente_telefono UNIQUE (telefono)
);
CREATE INDEX idx_cliente_nombre ON cliente (nombre);